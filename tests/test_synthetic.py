"""Fully synthetic tests. No CAD models, binaries, or fixtures are bundled."""
import hashlib
from pathlib import Path
import subprocess
import sys
import tempfile
from types import SimpleNamespace
import unittest

SRC = Path(__file__).resolve().parents[1] / "src"
sys.path.insert(0, str(SRC))

from geometry import Geometry, UnsupportedGeometry, _planar_face
from runtime import rhino3dm as rh
from strict_planarity import exact_plane

def build_3dm(path):
    model = rh.File3dm()
    model.Settings.ModelUnitSystem = rh.UnitSystem.Millimeters
    model.Settings.ModelAbsoluteTolerance = 0.01
    layer = rh.Layer()
    layer.Name = "Synthetic solids"
    layer_index = model.Layers.Add(layer)
    attr = rh.ObjectAttributes()
    attr.LayerIndex = layer_index
    attr.Name = "Synthetic closed box"
    box = rh.Brep.CreateFromBox(rh.Box(rh.BoundingBox(
        rh.Point3d(0, 0, 0), rh.Point3d(120, 80, 40))))
    assert box is not None and box.IsSolid
    model.Objects.AddBrep(box, attr)
    inst_idx = model.InstanceDefinitions.Add(
        "Synthetic shared block", "Generated by test", "", "",
        rh.Point3d(0, 0, 0), (box,), (attr,))
    assert inst_idx >= 0
    did = model.InstanceDefinitions[inst_idx].Id
    for xx in (200, 400):
        model.Objects.AddInstanceObject(
            rh.InstanceReference(did, rh.Transform.Translation(xx, 0, 0)), attr)
    assert model.Write(str(path), 8)

class SyntheticTests(unittest.TestCase):
    def test_numeric_predicate_does_not_flatten(self):
        planar = [(0, 0, 0), (2, 0, 0), (2, 2, 1e-8), (0, 2, 0)]
        self.assertIsNone(exact_plane(planar))
        self.assertIsNotNone(exact_plane(planar, roundoff_tol=1e-6))
        ugly = planar[:2] + [(2, 2, 0.002)] + planar[3:]
        self.assertIsNone(exact_plane(ugly, roundoff_tol=1e-6))

    def test_closed_topology_uses_original_brep_vertex_positions(self):
        corners = [(0, 0, 0), (120, 0, 0), (120, 80, 0), (0, 80, 0)]
        domain = SimpleNamespace(T0=0, T1=1)
        face = SimpleNamespace(
            Loops=[SimpleNamespace(
                LoopType="BrepLoopType.Outer",
                Trims=[SimpleNamespace(EdgeIndex=i, IsReversed=False,
                                       StartVertexIndex=i, EndVertexIndex=(i+1)%4)
                       for i in range(4)])],
            Domain=lambda _: domain,
            NormalAt=lambda *_: rh.Vector3d(0, 0, 1),
            OrientationIsReversed=False)
        brep = SimpleNamespace(
            Edges=[SimpleNamespace(TryGetPolyline=(lambda i: lambda: [
                rh.Point3d(*corners[i]),
                rh.Point3d(corners[(i+1)%4][0] + 1e-9, *corners[(i+1)%4][1:])
            ])(i)) for i in range(4)],
            Vertices=[SimpleNamespace(Location=rh.Point3d(*p)) for p in corners])
        out = Geometry()
        _planar_face(out, brep, face, 0.1, roundoff_tol=1e-6)
        self.assertEqual(len(out.faces), 1)
        self.assertEqual(set(map(tuple, out.vertices)), set(corners))
        with self.assertRaises(UnsupportedGeometry):
            _planar_face(Geometry(), brep, face, 0.1, roundoff_tol=1e-12)

    def test_native_roundtrip_box_and_reused_block(self):
        import json
        with tempfile.TemporaryDirectory() as t:
            base = Path(t)
            source = base / "synthetic.3dm"
            output = base / "synthetic.skp"
            build_3dm(source)
            source_hash = hashlib.sha256(source.read_bytes()).hexdigest()
            run = subprocess.run(
                [sys.executable, "-B", str(SRC / "convert.py"), str(source),
                 "-o", str(output)], capture_output=True, text=True,
                encoding="utf-8")
            self.assertEqual(run.returncode, 0, run.stdout + run.stderr)
            self.assertTrue(output.is_file())
            self.assertEqual(hashlib.sha256(source.read_bytes()).hexdigest(), source_hash)
            report = json.loads((base / "synthetic_检查" / "转换报告.json")
                                .read_text(encoding="utf-8"))
            self.assertTrue(report["source_unchanged"])
            self.assertTrue(report["verification"]["passed"])
            self.assertEqual(report["whole_surface_gate"]["candidate_surface_occurrences"], 0)
            self.assertEqual(report["instance_record_count"], 2)
            self.assertEqual(report["definition_count"], 1)

if __name__ == "__main__":
    unittest.main()
